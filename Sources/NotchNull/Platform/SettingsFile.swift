import Combine
import SwiftUI

/// One setting as it appears in ~/.notchnull/settings.json: "look.accent", its type and range,
/// how to read it from Preferences and how to apply a value (returning an error message).
struct SettingField {
    let key: String
    let type: String
    let summary: String
    let read: @MainActor (Preferences) -> JSONValue
    let write: @MainActor (Preferences, JSONValue) -> String?
}

/// Keeps ~/.notchnull/settings.json and the app's settings the same, in both directions: edit
/// the file and the notch changes live; change a setting in the app and the file is rewritten.
@MainActor
final class SettingsFile: ObservableObject {
    static let shared = SettingsFile()

    /// Problems in the last file read (unknown keys, wrong types), shown in Settings and status.json.
    @Published private(set) var errors: [String] = []

    private var lastWritten: Data?
    private var watcher: FileWatcher?
    private var cancellables: Set<AnyCancellable> = []
    private let preferences = Preferences.shared

    func start() {
        NotchHome.writeIfChanged(Self.reference, to: NotchHome.settingsReference)
        if let data = try? Data(contentsOf: NotchHome.settings) {
            apply(data)
        }
        write()
        preferences.objectWillChange
            .debounce(for: .milliseconds(400), scheduler: RunLoop.main)
            .sink { [weak self] _ in self?.write() }
            .store(in: &cancellables)
        let watcher = FileWatcher(paths: [NotchHome.root]) { [weak self] paths in
            guard paths.contains(where: { $0.hasSuffix("/settings.json") }) else { return }
            MainActor.assumeIsolated { self?.fileChanged() }
        }
        watcher.start()
        self.watcher = watcher
    }

    private func fileChanged() {
        guard let data = try? Data(contentsOf: NotchHome.settings), data != lastWritten else { return }
        apply(data)
    }

    /// Applies settings. Only values that differ are set, and each field validates its own value,
    /// so one bad line never blocks the rest. Problems in the file itself are kept in `errors`;
    /// a patch from the CLI or API only returns its problems, since the file does not hold them.
    @discardableResult
    func apply(_ data: Data, isPatch: Bool = false) -> [String] {
        guard let root = JSONValue.parse(data), let sections = root.object else {
            let problem = isPatch ? "The patch is not a JSON object." : "settings.json is not a JSON object. Nothing was applied; fix the syntax and save again."
            if !isPatch {
                errors = [problem]
                NotchStatus.write()
            }
            return [problem]
        }
        var problems: [String] = []
        let known = Set(Self.fields.map(\.key))
        for (section, value) in sections {
            guard let entries = value.object else {
                problems.append("\"\(section)\" should be an object of settings.")
                continue
            }
            for key in entries.keys where !known.contains("\(section).\(key)") {
                problems.append("Unknown setting \(section).\(key). See settings.reference.md.")
            }
        }
        withAnimation(Motion.state) {
            for field in Self.fields {
                guard let value = root.value(at: field.key), value != field.read(preferences) else { continue }
                if let problem = field.write(preferences, value) { problems.append("\(field.key): \(problem)") }
            }
        }
        if !isPatch {
            errors = problems
            NotchStatus.write()
        }
        if !problems.isEmpty { Log.app.notice("settings \(isPatch ? "patch" : "file"): \(problems.count) problem(s)") }
        return problems
    }

    /// The current settings as the file shows them, grouped by section.
    func snapshot() -> JSONValue {
        var sections: [String: [String: JSONValue]] = [:]
        for field in Self.fields {
            let parts = field.key.split(separator: ".", maxSplits: 1).map(String.init)
            sections[parts[0], default: [:]][parts[1]] = field.read(preferences)
        }
        return .object(sections.mapValues { .object($0) })
    }

    private func write() {
        guard let data = try? JSONSerialization.data(withJSONObject: snapshot().any, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]) else { return }
        guard data != lastWritten, (try? Data(contentsOf: NotchHome.settings)) != data else {
            lastWritten = data
            return
        }
        lastWritten = data
        try? data.write(to: NotchHome.settings, options: .atomic)
    }

    // MARK: Reference

    static var reference: String {
        var lines = [
            "# settings.json reference",
            "",
            "Generated by NotchNull \(Bundle.main.object(forInfoDictionaryKey: "CFBundleShortVersionString") as? String ?? "dev"). Edit ~/.notchnull/settings.json; changes apply as soon as the file is saved. Unknown keys and bad values are reported in ~/.notchnull/status.json and in Settings › Build.",
            "",
            "| Key | Type | What it does |",
            "|---|---|---|",
        ]
        lines += fields.map { "| `\($0.key)` | \($0.type) | \($0.summary) |" }
        return lines.joined(separator: "\n") + "\n"
    }

