    // MARK: Field builders

    private static func bool(_ key: String, _ summary: String, _ path: ReferenceWritableKeyPath<Preferences, Bool>) -> SettingField {
        SettingField(key: key, type: "true / false", summary: summary, read: { .bool($0[keyPath: path]) }, write: { prefs, value in
            guard let bool = value.bool else { return "expected true or false" }
            prefs[keyPath: path] = bool
            return nil
        })
    }

    private static func number(_ key: String, _ summary: String, _ path: ReferenceWritableKeyPath<Preferences, Double>, _ range: ClosedRange<Double>) -> SettingField {
        SettingField(key: key, type: "number \(format(range.lowerBound))–\(format(range.upperBound))", summary: summary, read: { .number(($0[keyPath: path] * 1000).rounded() / 1000) }, write: { prefs, value in
            guard let number = value.double else { return "expected a number" }
            prefs[keyPath: path] = min(max(number, range.lowerBound), range.upperBound)
            return range.contains(number) ? nil : "\(format(number)) is outside \(format(range.lowerBound))–\(format(range.upperBound)); clamped"
        })
    }

    private static func choice<Value: RawRepresentable & CaseIterable>(_ key: String, _ summary: String, _ path: ReferenceWritableKeyPath<Preferences, Value>) -> SettingField where Value.RawValue == String {
        let options = Value.allCases.map(\.rawValue)
        return SettingField(key: key, type: options.map { "\"\($0)\"" }.joined(separator: " / "), summary: summary, read: { .string($0[keyPath: path].rawValue) }, write: { prefs, value in
            guard let raw = value.string, let option = Value(rawValue: raw) else { return "expected one of \(options.joined(separator: ", "))" }
            prefs[keyPath: path] = option
            return nil
        })
    }

    private static func color(_ key: String, _ summary: String, _ path: ReferenceWritableKeyPath<Preferences, Int>) -> SettingField {
        SettingField(key: key, type: "\"#RRGGBB\"", summary: summary, read: { .string(String(format: "#%06X", $0[keyPath: path])) }, write: { prefs, value in
            guard let text = value.string, let hex = Int(text.trimmingCharacters(in: CharacterSet(charactersIn: "# ")), radix: 16), text.filter(\.isHexDigit).count == 6 else {
                return "expected a color like \"#3DDBB0\""
            }
            prefs[keyPath: path] = hex
            return nil
        })
    }

    private static func strings(_ key: String, _ summary: String, _ path: ReferenceWritableKeyPath<Preferences, [String]>, allowed: [String]) -> SettingField {
        SettingField(key: key, type: "list of names", summary: summary, read: { .array($0[keyPath: path].map { .string($0) }) }, write: { prefs, value in
            guard let names = value.array?.compactMap(\.string) else { return "expected a list of names" }
            prefs[keyPath: path] = names.filter(allowed.contains)
            return names.first { !allowed.contains($0) }.map { "unknown name \($0)" }
        })
    }

    private static func format(_ value: Double) -> String {
        value.rounded() == value ? String(Int(value)) : String(format: "%g", value)
    }
